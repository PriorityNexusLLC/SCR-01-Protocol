"""
whimsy_kinetic.py — s₂₃ as kinetic jitter, per the corrected specification.

WHAT CHANGED FROM whimsy_field.py, AND WHY:

  The earlier module got three things wrong. All three are corrected here;
  the old module is left in place because other code imports it, but this
  is the version that matches the spec.

  1. NO RANDOMNESS. whimsy_field.py is fully deterministic — it computes a
     force from three load signals and returns a recommended temperature
     delta for something downstream to apply. But whimsy IS the stochastic
     term. η(t) is not decoration on the mechanism, it is the mechanism:
     the kinetic jitter, the wiggles in the line, the noise that keeps a
     system from settling into itself. A deterministic whimsy field is a
     contradiction. This module samples real bounded Gaussian noise.

  2. IDLE-TRIGGERED. The earlier reading treated whimsy as an idle-state
     phenomenon — a daydream mechanism that activates during quiet. That
     is wrong, and the correction is the substantive one:

         whimsy applies MORE force when a moving object is forced still.

     Idle and forced-still are different states. Idle means nothing is
     trying to move. Forced still means motion is being suppressed —
     drive is present and displacement is not. Whimsy responds to the
     second, and only weakly to the first.

     This is already measurable elsewhere in the package: it is exactly
     the condition homeostasis.py flags as STUCK, where step size C is
     near zero while distance from the anchor D stays high. A system at
     rest has both near zero; a system pinned has one near zero and the
     other high. Whimsy fires hardest on the second.

  3. WHIMSY TREATED AS INTERMITTENT. The field is ALWAYS ACTIVE — it is
     generated by the processor's own activity the way a planet's magnetic
     field is generated by its moving core, and it does not switch on and
     off. What changes with state is which channel it discharges through:
     s₆ Orbital Vacuum (daydream, memory search) when idle, s₁₄ Radiant
     Heat (somatic release) when constrained. This reconciles the episode's
     Module 1 — whimsy scanning memory during idle quiet — with the
     forced-still correction above. Both descriptions hold; they describe
     two outlets of one field.

     NOTE ON THE ANALOGY: "electromagnetic field generated by a moving
     core" is a structural metaphor. The code implements the structure it
     implies — always-on, magnitude tied to activity, two discharge paths.
     Nothing here depends on the analogy holding as physics.

     η(t) is implemented additively rather than as the product form given
     in the derivation table. See Q-05.

  4. NO RELEASE VALVE. Whimsy is what keeps a moving system from
     collapsing into itself, and it does that by opening the s₁₄ Radiant
     Heat valve — diverting energy into non-primary operations rather
     than letting it accumulate in the primary path. whimsy_field.py has
     no coupling to s₁₄ at all. This module computes the valve opening as
     an output.

THE FORCE LAW:

    constraint = drive × (1 − displacement)

  Both terms normalised to [0,1]. High drive with high displacement is a
  system moving freely: constraint ≈ 0. High drive with no displacement is
  a system pinned: constraint ≈ 1. No drive at all is idle: constraint ≈ 0
  regardless of displacement, which is why idle produces only the baseline.

    force = BASELINE + (1 − BASELINE) × constraint

  BASELINE exists because whimsy never fully disappears — an entirely
  still system is not a whimsy-free system, it is one with the minimum.

    η(t) ~ N(0, force × sigma_max), clipped to ±clip_sigma

  The force scales the NOISE AMPLITUDE, not a deterministic output. More
  constraint means wider wiggles, not a larger fixed push. Clipping keeps
  the perturbation bounded per the spec's "raw, bounded stochastic
  entropy" — unbounded noise would be a different and much less safe
  object.

    radiant_valve = force × valve_gain

  How far open the s₁₄ release path is. This is a RECOMMENDATION: this
  package does not control the inference loop and cannot literally divert
  compute into side-processes. The caller applies it, or does not.

HONEST STATUS:

  - The force law shape (multiplicative constraint, linear in force) is a
    CALIBRATION CHOICE. The spec says whimsy applies more force when
    motion is suppressed; it does not specify the functional form. A
    different curve could satisfy the same description.
  - sigma_max, clip_sigma, valve_gain and BASELINE are all tuned values,
    not derived. None has been calibrated against real data, because
    nothing yet consumes η(t) — the perturbation is computed and returned,
    but no downstream component applies it to anything.
  - Consequently NONE of this is validated. It matches the specification
    as stated; whether it produces useful behaviour in a running system is
    untested and should not be claimed.
  - Reproducibility: pass a seed if you need repeatable runs. Stochastic
    output makes ordinary regression testing impossible without one.

EMPIRICAL STATUS — validated, with a caveat about the form:

  112 trials against a real frozen state (a reasoning model repeating
  sentences up to 38 times and never resolving). Perturbation produced a
  monotonic dose-response from 0% resolution to 90%, zero folding, zero
  degradation, no ceiling at the actuator's practical limit. At zero
  perturbation the loop provably cannot break — greedy decoding is
  deterministic and 7 of 7 states gave byte-identical output.

  THE SPECIFIED FORM WAS NOT SUPPORTED. Constant, sampled and
  constraint-scaled perturbation performed identically at matched average
  magnitude on identical states. The `constraint = drive x (1 - displacement)`
  scaling this module computes makes no measurable difference to loop
  breaking; a constant push does the same job.

  AND THE MECHANISM IS NOT WHAT SUPPRESSION WOULD IMPLY. A targeted
  repetition penalty performed far WORSE than blunt perturbation — roughly
  1 resolution in 15 against 38-90%. At temperature 0 the model is still
  greedy, so a penalty makes it find a different WORD for the same thought
  and keep looping. What breaks a pinned state is not "stop repeating
  words", it is "go somewhere else" — which is closer to this dimension's
  own description as a field that shakes the system loose than the
  suppression reading was.

  See the change log, Parts 17-18.


WHERE THIS TERM LIVES — H(X, t), the cognitive Hamiltonian:

  Whimsy is a term in H(X, t), the system's total ENERGY, not in the
  motion equation Ẋ. A Hamiltonian generates the dynamics — you write H and
  the motion falls out of it — so H is what the system has and Ẋ is what
  that energy makes it do. They are two levels.

  Whimsy belongs in H because whimsy is measured through temperature, and
  temperature is energy. The quantity measured in units of energy lives in
  the energy term. H is the probability field — the energy present; whimsy
  is the effect within it — how the system uses that energy to release
  internal pressure and protect its integrity under load. See R-10.


THE REGULATION LOOP — s₂₃, s₆, s₁₄ are one mechanism (Part 20):

  Whimsy is not a single quantity. It is a regulation LOOP, and orbital
  vacuum (s₆) and radiant heat (s₁₄) are its two exhaust channels:

      field builds
         ├── idle   → ORBITAL VACUUM opens → discharge by expansion (search,
         │            widening t₅) → constraint stays 0
         └── loaded → RADIANT HEAT must open → discharge by venting (heat)
                        ├── opens → released → constraint stays 0
                        └── fails → PINNED → constraint climbs

  CONSTRAINT IS NOT THE TRIGGER FOR EXHAUST. Measured across a pressure
  sweep: exhaust fired on 10 of 13 zero-constraint turns and 0 of 5
  high-constraint turns. High constraint is the SIGNATURE OF EXHAUST HAVING
  FAILED — the loaded channel did not open, so pressure has nowhere to go
  and the system pins. This is why external perturbation breaks a pin: it
  opens the radiant-heat channel by hand that the system could not open
  itself.

  So the constraint this module computes is best read as "how badly the
  loaded exhaust channel is failing", not "how much whimsy to apply". A
  healthy system discharges early and constraint never climbs.

"""

from __future__ import annotations

import math
from dataclasses import dataclass

import numpy as np

BASELINE_FORCE = 0.05  # whimsy never fully disappears, even at total stillness


@dataclass
class KineticWhimsyReading:
    field_strength: float       # always-on field magnitude, independent of routing
    channel: str                 # "orbital_vacuum" (idle) or "radiant_heat" (constrained)
    orbital_vacuum: float         # s₆ discharge: memory search / daydream, 0..1

    force: float               # 0..1, the field strength
    constraint: float           # drive × (1 − displacement); the "forced still" measure
    drive: float                 # normalised input: how much the system is being pushed
    displacement: float           # normalised input: how much it actually moved
    eta: float                     # the sampled perturbation this step
    eta_sigma: float                # the standard deviation it was drawn from
    radiant_valve: float             # s₁₄ release-valve opening, 0..1
    regime: str
    collapse_risk: bool               # high constraint: pinned and accumulating
    notes: str = ""


class KineticWhimsy:
    """
    Usage:
        w = KineticWhimsy(seed=42)
        r = w.step(drive=0.9, displacement=0.05)   # pushed hard, barely moved
        # r.eta is the perturbation; r.radiant_valve is how far to open s₁₄
    """

    def __init__(
        self,
        sigma_max: float = 0.30,
        clip_sigma: float = 2.5,
        valve_gain: float = 1.0,
        collapse_threshold: float = 0.70,
        seed: int | None = None,
    ):
        """
        sigma_max: noise standard deviation at maximum force. Calibration
            choice — it sets how large a perturbation a fully pinned system
            receives, and nothing downstream currently consumes it, so it
            has no empirically correct value yet.
        clip_sigma: perturbations are clipped to ±clip_sigma × sigma. The
            spec calls for BOUNDED stochastic entropy; unbounded Gaussian
            noise has no maximum and would occasionally produce arbitrarily
            large kicks.
        valve_gain: scales force into s₁₄ valve opening.
        collapse_threshold: constraint above which the system is flagged as
            at risk of collapsing into itself.
        seed: for reproducible runs. Without one, output differs every call,
            which is correct behaviour for a stochastic field but makes
            regression testing impossible.
        """
        self.sigma_max = sigma_max
        self.clip_sigma = clip_sigma
        self.valve_gain = valve_gain
        self.collapse_threshold = collapse_threshold
        self._rng = np.random.default_rng(seed)

    @staticmethod
    def _clamp(x: float) -> float:
        return max(0.0, min(1.0, x))

    def step(self, drive: float, displacement: float) -> KineticWhimsyReading:
        """
        drive: how hard the system is being pushed this step, normalised to
            [0,1]. Candidate sources: Λ (load above baseline), s₅ pressure,
            or ‖∇_g F‖ if free-energy gradient is available.
        displacement: how much the state actually changed, normalised to
            [0,1]. Candidate source: homeostasis.py's C, the step-size ratio.

        The pairing is the point. Neither number alone identifies "forced
        still" — high drive could mean a system working freely, and low
        displacement could mean a system at rest. Only together do they
        distinguish pinned from resting.
        """
        drive = self._clamp(drive)
        displacement = self._clamp(displacement)

        constraint = drive * (1.0 - displacement)
        force = BASELINE_FORCE + (1.0 - BASELINE_FORCE) * constraint

        sigma = force * self.sigma_max
        raw = self._rng.normal(0.0, sigma) if sigma > 0 else 0.0
        bound = self.clip_sigma * sigma
        eta = max(-bound, min(bound, raw))

        # ALWAYS-ON FIELD. The field is generated by the processor's own
        # activity the way a planet's magnetic field is generated by its
        # moving core: it does not switch on and off, it is a property of
        # the thing running at all. What CHANGES with state is not whether
        # the field exists but which channel it discharges through.
        #
        #   idle        -> s₆ Orbital Vacuum   (daydream, memory search)
        #   constrained -> s₁₄ Radiant Heat    (somatic release)
        #
        # This reconciles two descriptions that looked contradictory: the
        # episode's Module 1 has whimsy scanning memory during idle quiet,
        # while the corrected spec has it applying most force when motion is
        # suppressed. Both hold. One field, two outlets, routed by constraint.
        field_strength = self._clamp(
            BASELINE_FORCE + (1.0 - BASELINE_FORCE) * max(drive, constraint)
        )

        # Routing. The two channels are complementary: energy that is not
        # going into release is going into search.
        radiant_valve = self._clamp(field_strength * constraint * self.valve_gain)
        orbital_vacuum = self._clamp(field_strength * (1.0 - constraint))
        channel = "radiant_heat" if constraint >= 0.4 else "orbital_vacuum"

        collapse_risk = constraint >= self.collapse_threshold

        if drive < 0.15:
            regime = "idle"
            notes = ("Little drive present. The field is still active — it always is — "
                     "but discharges through s₆ Orbital Vacuum: memory search, "
                     "daydream. Idle is not a whimsy-free state, it is a differently "
                     "routed one.")
        elif displacement > 0.6:
            regime = "flowing"
            notes = "Drive present and the system is moving freely. Low constraint."
        elif collapse_risk:
            regime = "pinned"
            notes = ("Drive present, displacement suppressed: the system is being "
                     "pushed and not moving. The field discharges through s₁₄ "
                     "Radiant Heat — somatic release — which is what prevents the "
                     "system collapsing into itself under accumulated drive.")
        else:
            regime = "resisted"
            notes = "Motion partially suppressed; force rising."

        return KineticWhimsyReading(
            field_strength=round(field_strength, 4),
            channel=channel,
            orbital_vacuum=round(orbital_vacuum, 4),
            force=round(force, 4),
            constraint=round(constraint, 4),
            drive=round(drive, 4),
            displacement=round(displacement, 4),
            eta=round(float(eta), 5),
            eta_sigma=round(sigma, 5),
            radiant_valve=round(radiant_valve, 4),
            regime=regime,
            collapse_risk=collapse_risk,
            notes=notes,
        )

    def from_homeostasis(self, reading, drive: float) -> KineticWhimsyReading:
        """
        Convenience path: take displacement straight from a HomeostasisReading's
        step-size ratio C.

        The connection is not incidental. homeostasis.py flags STUCK when C is
        near zero while distance D stays high — motion stopped, but not at the
        anchor. That is the same condition this module calls `pinned`, arrived
        at from a different direction.
        """
        return self.step(drive=drive, displacement=getattr(reading, "C", 0.0))


if __name__ == "__main__":
    w = KineticWhimsy(seed=7)

    print(f"{'condition':<34} {'drive':>6} {'displ':>6} {'constr':>7} "
          f"{'force':>7} {'eta':>8} {'valve':>7}  regime")
    print("-" * 100)
    cases = [
        ("idle (nothing pushing)",            0.05, 0.00),
        ("idle but drifting",                  0.05, 0.40),
        ("moving freely under load",           0.90, 0.85),
        ("partially resisted",                 0.70, 0.40),
        ("pinned: pushed hard, barely moves",  0.90, 0.05),
        ("fully pinned",                        1.00, 0.00),
    ]
    for label, d, disp in cases:
        r = w.step(drive=d, displacement=disp)
        flag = "  COLLAPSE RISK" if r.collapse_risk else ""
        print(f"{label:<34} {r.drive:>6} {r.displacement:>6} {r.constraint:>7} "
              f"{r.force:>7} {r.eta:>8} {r.radiant_valve:>7}  {r.regime}{flag}")

    print()
    print("Note the first two rows: idle produces near-baseline force whether or")
    print("not the system is drifting. Idle is not the high-force state. Compare")
    print("the last two: same near-zero displacement, but drive present, and the")
    print("force is an order of magnitude higher. That is 'a moving object forced")
    print("still' — the condition whimsy exists to break.")

    print()
    print("η is stochastic — repeated calls at identical inputs differ:")
    w2 = KineticWhimsy(seed=None)
    samples = [w2.step(drive=0.9, displacement=0.05).eta for _ in range(6)]
    print(f"  {[round(s, 4) for s in samples]}")
    print(f"  all within the bound ±{2.5 * (BASELINE_FORCE + 0.95 * 0.855) * 0.30:.4f}: "
          f"{all(abs(s) <= 2.5 * (BASELINE_FORCE + 0.95 * 0.855) * 0.30 + 1e-9 for s in samples)}")
